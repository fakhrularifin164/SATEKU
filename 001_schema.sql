begin;
create extension if not exists pgcrypto with schema extensions;
create table public.sateku_staff (
 user_id uuid primary key references auth.users(id) on delete cascade,
 role text not null check (role in ('admin','cashier','kitchen')),
 created_at timestamptz not null default now()
);
alter table public.sateku_staff enable row level security;
create policy staff_own_role on public.sateku_staff for select to authenticated using (user_id=auth.uid());
create function public.sateku_role() returns text language sql stable security definer set search_path=public,pg_temp as $$ select role from public.sateku_staff where user_id=auth.uid() $$;
revoke all on function public.sateku_role() from public;
grant execute on function public.sateku_role() to authenticated;
create table public.sateku_products (
 id bigint generated by default as identity primary key,
 name text not null check(length(name) between 1 and 100),
 price integer not null check(price between 1000 and 10000000),
 category text not null, description text not null default '', image text not null default '/assets/hero.webp',
 badge text not null default '', available boolean not null default true
);
alter table public.sateku_products enable row level security;
create policy public_catalog on public.sateku_products for select to anon,authenticated using(true);
create policy admin_catalog on public.sateku_products for all to authenticated using(public.sateku_role()='admin') with check(public.sateku_role()='admin');
create table public.sateku_orders (
 id uuid primary key default gen_random_uuid(), request_id uuid not null unique,
 tracking_hash text not null, order_number text not null unique,
 customer_name text not null, phone text not null, address text not null default '', note text not null default '',
 method text not null check(method in ('DineIn','Pickup','Delivery')), table_number integer,
 payment_method text not null check(payment_method in ('qris_manual','cash')),
 payment_status text not null default 'unpaid' check(payment_status in ('unpaid','verified')),
 status text not null default 'new' check(status in ('new','accepted','cooking','ready','completed','cancelled')),
 subtotal integer not null, shipping integer not null, total integer not null,
 customer_claimed_at timestamptz, verified_at timestamptz, verified_by uuid references auth.users(id),
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index orders_created on public.sateku_orders(created_at desc);
alter table public.sateku_orders enable row level security;
create policy cashier_read on public.sateku_orders for select to authenticated using(public.sateku_role() in ('admin','cashier'));
create table public.sateku_items (
 id bigint generated always as identity primary key, order_id uuid not null references public.sateku_orders(id) on delete cascade,
 product_id bigint not null references public.sateku_products(id), name text not null,
 qty integer not null, portion integer not null, spice integer not null, sauce text not null,
 extra integer not null, note text not null, unit_price integer not null
);
create index item_order on public.sateku_items(order_id);
alter table public.sateku_items enable row level security;
create policy cashier_items_read on public.sateku_items for select to authenticated using(public.sateku_role() in ('admin','cashier'));
-- Only non-contact information is replicated to kitchen staff.
create table public.sateku_kitchen (
 order_id uuid primary key references public.sateku_orders(id), order_number text not null,
 method text not null, table_number integer, note text not null, items jsonb not null,
 status text not null check(status in ('accepted','cooking','ready','completed','cancelled')),
 created_at timestamptz not null, updated_at timestamptz not null default now()
);
alter table public.sateku_kitchen enable row level security;
create policy kitchen_read on public.sateku_kitchen for select to authenticated using(public.sateku_role() in ('admin','cashier','kitchen'));
revoke all on public.sateku_staff,public.sateku_products,public.sateku_orders,public.sateku_items,public.sateku_kitchen from anon,authenticated;
grant select on public.sateku_products to anon,authenticated;
grant select on public.sateku_staff,public.sateku_orders,public.sateku_items,public.sateku_kitchen to authenticated;
grant insert,update,delete on public.sateku_products to authenticated;
grant usage,select on sequence public.sateku_products_id_seq to authenticated;
create function public.sateku_place_order(p_request_id uuid,p_token text,p_items jsonb,p_name text,p_phone text,p_address text,p_note text,p_method text,p_table text,p_payment text)
returns jsonb language plpgsql security definer set search_path=public,extensions,pg_temp as $$
declare o public.sateku_orders; p public.sateku_products; item jsonb; q int; portions int; sp int; ex int; su text; nt text; sub int:=0; delivery int; unit int; num text; tokhash text;
begin
 if p_token is null or length(p_token)<40 or length(p_token)>200 then raise exception 'Referensi pelanggan tidak valid'; end if;
 tokhash:=encode(digest(p_token,'sha256'),'hex');
 -- Serializes retries of the same request; the secret token must also match.
 perform pg_advisory_xact_lock(hashtextextended(p_request_id::text,0));
 select * into o from public.sateku_orders where request_id=p_request_id;
 if found then
  if o.tracking_hash<>tokhash then raise exception 'Referensi tidak cocok'; end if;
  return jsonb_build_object('id',o.id,'order_number',o.order_number,'total',o.total,'status',o.status);
 end if;
 if p_name is null or length(trim(p_name)) not between 2 and 80 or p_phone is null or p_phone !~ '^\+?[0-9 ()-]{9,20}$' then raise exception 'Nama atau WhatsApp tidak valid'; end if;
 if p_method is null or p_method not in ('DineIn','Pickup','Delivery') then raise exception 'Layanan tidak valid'; end if;
 if p_method='DineIn' and (p_table is null or p_table !~ '^[1-9][0-9]{0,2}$') then raise exception 'Isi nomor meja 1–999'; end if;
 if length(coalesce(p_address,''))>500 or (p_method='Delivery' and length(trim(coalesce(p_address,'')))<10) then raise exception 'Alamat tidak valid'; end if;
 if length(coalesce(p_note,''))>500 then raise exception 'Catatan terlalu panjang'; end if;
 if p_payment is null or p_payment not in ('qris_manual','cash') then raise exception 'Metode pembayaran tidak valid'; end if;
 if p_items is null or jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items) not between 1 and 30 then raise exception 'Keranjang tidak valid'; end if;
 if (select count(*) from public.sateku_orders where phone=p_phone and created_at>now()-interval '1 minute')>=3 then raise exception 'Terlalu banyak pesanan. Tunggu sebentar.'; end if;
 -- All prices and stock come from database, never from browser totals.
 for item in select * from jsonb_array_elements(p_items) loop
  select * into p from public.sateku_products where id=(item->>'id')::bigint and available=true for share;
  if not found then raise exception 'Produk tidak tersedia'; end if;
  q:=(item->>'qty')::int; portions:=(item->>'portion')::int; sp:=(item->>'spice')::int; ex:=(item->>'extra')::int; su:=item->>'sauce';nt:=coalesce(item->>'note','');
  if q is null or q not between 1 and 50 or portions is null or portions not in (1,2) or sp is null or sp not between 0 and 5 or ex is null or ex not in (0,4000,5000) or length(nt)>300 then raise exception 'Variasi atau jumlah tidak valid'; end if;
  if p.category='Minuman' then
   if portions<>1 or ex<>0 or sp<>0 or su is distinct from 'Tanpa bumbu' then raise exception 'Variasi minuman tidak valid'; end if;
  elsif p.category in ('Menu Berkuah','Nasi Goreng') then
   if su is distinct from 'Tanpa bumbu' then raise exception 'Bumbu masakan tidak valid'; end if;
  elsif su is null or su not in ('Kacang','Kecap','Sambal taichan') then raise exception 'Bumbu tidak valid'; end if;
  sub:=sub+(p.price*portions+ex)*q;
 end loop;
 delivery:=case when p_method='Delivery' then 10000 else 0 end;
 if sub+delivery>5000000 then raise exception 'Maksimum pesanan Rp5.000.000'; end if;
 num:='SK-'||to_char(now() at time zone 'Asia/Jakarta','YYMMDD')||'-'||upper(encode(gen_random_bytes(5),'hex'));
 insert into public.sateku_orders(request_id,tracking_hash,order_number,customer_name,phone,address,note,method,table_number,payment_method,subtotal,shipping,total)
 values(p_request_id,tokhash,num,trim(p_name),p_phone,coalesce(p_address,''),coalesce(p_note,''),p_method,case when p_method='DineIn' then p_table::int else null end,p_payment,sub,delivery,sub+delivery) returning * into o;
 for item in select * from jsonb_array_elements(p_items) loop
  select * into p from public.sateku_products where id=(item->>'id')::bigint;
  insert into public.sateku_items(order_id,product_id,name,qty,portion,spice,sauce,extra,note,unit_price)
  values(o.id,p.id,p.name,(item->>'qty')::int,(item->>'portion')::int,(item->>'spice')::int,item->>'sauce',(item->>'extra')::int,coalesce(item->>'note',''),p.price*(item->>'portion')::int+(item->>'extra')::int);
 end loop;
 return jsonb_build_object('id',o.id,'order_number',o.order_number,'total',o.total,'subtotal',o.subtotal,'shipping',o.shipping,'status',o.status);
end $$;
create function public.sateku_track(p_id uuid,p_token text) returns jsonb language plpgsql security definer set search_path=public,extensions,pg_temp as $$
declare o public.sateku_orders; its jsonb;
begin
 select * into o from public.sateku_orders where id=p_id and tracking_hash=encode(digest(p_token,'sha256'),'hex');
 if not found then raise exception 'Pesanan tidak ditemukan atau kunci pelacakan salah'; end if;
 select coalesce(jsonb_agg(jsonb_build_object('name',name,'qty',qty,'portion',portion,'spice',spice,'sauce',sauce,'extra',extra,'note',note,'unit_price',unit_price) order by id),'[]'::jsonb) into its from public.sateku_items where order_id=o.id;
 return jsonb_build_object('id',o.id,'order_number',o.order_number,'method',o.method,'table_number',o.table_number,'status',o.status,'payment_status',o.payment_status,'payment_method',o.payment_method,'customer_claimed_at',o.customer_claimed_at,'total',o.total,'created_at',o.created_at,'updated_at',o.updated_at,'items',its);
end $$;
create function public.sateku_claim_payment(p_id uuid,p_token text) returns boolean language plpgsql security definer set search_path=public,extensions,pg_temp as $$
begin
 update public.sateku_orders set customer_claimed_at=coalesce(customer_claimed_at,now()),updated_at=now() where id=p_id and tracking_hash=encode(digest(p_token,'sha256'),'hex') and payment_method='qris_manual' and status<>'cancelled';
 if not found then raise exception 'Pesanan QRIS tidak ditemukan'; end if;
 return true;
end $$;
create function public.sateku_cashier_action(p_id uuid,p_action text) returns boolean language plpgsql security definer set search_path=public,pg_temp as $$
declare o public.sateku_orders; its jsonb;
begin
 if coalesce(public.sateku_role(),'') not in ('admin','cashier') then raise exception 'Akses kasir diperlukan'; end if;
 select * into o from public.sateku_orders where id=p_id for update;
 if not found then raise exception 'Pesanan tidak ditemukan'; end if;
 if p_action='verify' then
  if o.status<>'new' or o.payment_status<>'unpaid' then raise exception 'Pembayaran sudah diproses atau pesanan dibatalkan'; end if;
  update public.sateku_orders set payment_status='verified',verified_at=now(),verified_by=auth.uid(),status='accepted',updated_at=now() where id=p_id;
  select jsonb_agg(jsonb_build_object('name',name,'qty',qty,'portion',portion,'spice',spice,'sauce',sauce,'extra',extra,'note',note) order by id) into its from public.sateku_items where order_id=p_id;
  insert into public.sateku_kitchen(order_id,order_number,method,table_number,note,items,status,created_at) values(p_id,o.order_number,o.method,o.table_number,o.note,its,'accepted',o.created_at);
 elsif p_action='complete' then
  if o.status<>'ready' then raise exception 'Pesanan belum siap'; end if;
  update public.sateku_orders set status='completed',updated_at=now() where id=p_id;
  update public.sateku_kitchen set status='completed',updated_at=now() where order_id=p_id;
 elsif p_action='cancel' then
  if o.status not in ('new','accepted') then raise exception 'Pesanan yang sedang dimasak/selesai tidak dapat dibatalkan di sini'; end if;
  update public.sateku_orders set status='cancelled',updated_at=now() where id=p_id;
  update public.sateku_kitchen set status='cancelled',updated_at=now() where order_id=p_id;
 else raise exception 'Aksi tidak valid'; end if;
 return true;
end $$;
create function public.sateku_kitchen_action(p_id uuid,p_status text) returns boolean language plpgsql security definer set search_path=public,pg_temp as $$
declare old_status text;
begin
 if coalesce(public.sateku_role(),'') not in ('admin','kitchen') then raise exception 'Akses dapur diperlukan'; end if;
 select status into old_status from public.sateku_orders where id=p_id and payment_status='verified' for update;
 if not found then raise exception 'Pesanan belum dikonfirmasi kasir'; end if;
 if not ((old_status='accepted' and p_status='cooking') or (old_status='cooking' and p_status='ready')) then raise exception 'Urutan status tidak valid'; end if;
 update public.sateku_orders set status=p_status,updated_at=now() where id=p_id;
 update public.sateku_kitchen set status=p_status,updated_at=now() where order_id=p_id;
 return true;
end $$;
revoke all on function public.sateku_place_order(uuid,text,jsonb,text,text,text,text,text,text,text),public.sateku_track(uuid,text),public.sateku_claim_payment(uuid,text),public.sateku_cashier_action(uuid,text),public.sateku_kitchen_action(uuid,text) from public;
grant execute on function public.sateku_place_order(uuid,text,jsonb,text,text,text,text,text,text,text),public.sateku_track(uuid,text),public.sateku_claim_payment(uuid,text) to anon,authenticated;
grant execute on function public.sateku_cashier_action(uuid,text),public.sateku_kitchen_action(uuid,text) to authenticated;
-- Supabase Realtime uses these table policies; kitchen cannot subscribe to private customer rows.
alter publication supabase_realtime add table public.sateku_orders,public.sateku_kitchen,public.sateku_products;
commit;
